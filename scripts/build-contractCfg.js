#!/usr/bin/env node
/**
 * scripts/build-contractCfg.js
 *
 * 从 artifacts/contracts/*.json + deployed-addresses.json 自动生成 src/contractCfg.js
 *
 * 之前 contractCfg.js 写死地址 → 每次 hardhat 重启就坏（wagmi-viem-gotchas §13）
 * 跑 `npm run build` 时自动跑这个（prebuild 钩子），让 ABI + 地址永远同步
 *
 * 用法：
 *   npm run build-contractCfg  # 手动跑
 *   npm run build              # 自动跑（prebuild 钩子）
 *   npm run start              # 自动跑（prestart 钩子，dev server 启动前）
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ARTIFACTS_CAT = path.join(ROOT, "artifacts/contracts/CatContract.sol/CatContract.json");
const ARTIFACTS_MKT = path.join(ROOT, "artifacts/contracts/CatMarketplace.sol/CatMarketplace.json");
const DEPLOYED = path.join(ROOT, "deployed-addresses.json");
const OUTPUT = path.join(ROOT, "src/contractCfg.js");

function die(msg) {
  console.error("\n[build-contractCfg] " + msg);
  console.error("[build-contractCfg] Aborting. 跑 `npm run deploy` 生成 deployed-addresses.json 后重试。\n");
  process.exit(1);
}

// 检查文件存在
if (!fs.existsSync(DEPLOYED)) {
  die("找不到 deployed-addresses.json — 还没部署合约？");
}
if (!fs.existsSync(ARTIFACTS_CAT) || !fs.existsSync(ARTIFACTS_MKT)) {
  die("找不到 artifacts/contracts/*.json — 跑 `npx hardhat compile` 重新编译");
}

const addrs = JSON.parse(fs.readFileSync(DEPLOYED, "utf8"));
const cat = JSON.parse(fs.readFileSync(ARTIFACTS_CAT, "utf8"));
const mkt = JSON.parse(fs.readFileSync(ARTIFACTS_MKT, "utf8"));

if (!addrs.catAddress || !addrs.marketAddress) {
  die("deployed-addresses.json 缺 catAddress / marketAddress");
}

// 过滤 ABI：留 function / event / constructor / error
const minAbi = (abi) =>
  abi.filter((x) => ["function", "event", "constructor", "error"].includes(x.type));

const cfg = {
  contractCatAddress: addrs.catAddress,
  contractCatABI: minAbi(cat.abi),
  contractMarketAddress: addrs.marketAddress,
  contractMarketABI: minAbi(mkt.abi),
};

const content =
  "// AUTO-GENERATED by scripts/build-contractCfg.js — 不要手改！\n" +
  "// 跑 `npm run deploy` 更新 deployed-addresses.json 后会自动重新生成。\n" +
  "// 手动重生成：`npm run build-contractCfg`\n\n" +
  "export const contractCfg = " + JSON.stringify(cfg, null, "\t") + ";\n";

fs.writeFileSync(OUTPUT, content);

const catFns = cfg.contractCatABI.filter((x) => x.type === "function").length;
const mktFns = cfg.contractMarketABI.filter((x) => x.type === "function").length;
console.log(
  "[build-contractCfg] ✓ wrote " + path.relative(ROOT, OUTPUT) +
  " (Cat: " + cfg.contractCatAddress.slice(0, 10) + "... " + catFns + " fns, " +
  "Market: " + cfg.contractMarketAddress.slice(0, 10) + "... " + mktFns + " fns)"
);
